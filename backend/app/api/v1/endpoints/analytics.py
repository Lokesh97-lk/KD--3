@router.get("/concept-graph")
def get_concept_graph(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Retrieve visual concept dependency DAG nodes with learner mastery states."""
    nodes = DependencyGraphService.get_user_graph(db, current_user.id)
    return nodes


@router.get("/recommendations")
def get_revision_recommendations(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Retrieve prioritized revision tasks generated by the Learning Debt engine."""
    return RecommendationEngine.get_user_recommendations(db, current_user.id)
