"""Learning Observatory, Debugging Intelligence, Concept DAG, and Analytics endpoints."""

from typing import List, Optional
from fastapi import APIRouter, Depends, Query
from sqlalchemy.orm import Session

from app.analytics.debugging_analyzer import DebuggingAnalyzer
from app.analytics.dependency_graph import DependencyGraphService
from app.analytics.learning_efficiency import LearningEfficiencyService
from app.analytics.recommendation_engine import RecommendationEngine
from app.api.dependencies import get_current_user, get_db
from app.models.user import User

router = APIRouter(prefix="/analytics", tags=["Analytics & Observatory"])


@router.get("/overview")
def get_observatory_overview(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Retrieve headline observatory learning telemetry computed from database sessions."""
    return LearningEfficiencyService.get_observatory_metrics(db, current_user.id)


@router.get("/topic-time")
def get_topic_time_distribution(
    range: str = Query("7d"),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Retrieve time breakdown across topics (reading, coding, debugging, testing)."""
    return LearningEfficiencyService.get_topic_time_distribution(db, current_user.id)


@router.get("/daily-trends")
def get_daily_trends(
    range: str = Query("7d"),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Retrieve daily activity and focus hours over 7 or 30 days."""
    days = 30 if "30" in range else 7
    return LearningEfficiencyService.get_daily_trends(db, current_user.id, days=days)


