"""Observatory, Learning Events, Debugging Patterns, Revision, and Skill Evidence models."""

import enum
from datetime import datetime
from typing import Any, Dict, Optional

from app.models.base import Base, TimestampMixin, UUIDPrimaryKeyMixin, utc_now
from sqlalchemy import JSON, Boolean, DateTime, Enum, Float, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column


class EventType(str, enum.Enum):
    LESSON_VIEW = "lesson_view"
    LESSON_COMPLETE = "lesson_complete"
    CODE_RUN = "code_run"
    CODE_SUBMIT = "code_submit"
    ASSESSMENT_START = "assessment_start"
    ASSESSMENT_FINISH = "assessment_finish"
    CONCEPT_STUDY = "concept_study"
    PROJECT_SUBMIT = "project_submit"


class RevisionReason(str, enum.Enum):
    WEAK_PREREQUISITE = "weak_prerequisite"
    RETENTION_DECAY = "retention_decay"
    REPEATED_ERRORS = "repeated_errors"
    UPCOMING_ASSESSMENT = "upcoming_assessment"


class RevisionUrgency(str, enum.Enum):
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class ErrorTrend(str, enum.Enum):
    IMPROVING = "improving"
    STABLE = "stable"
    REPEATING = "repeating"


class VerifiedLevel(str, enum.Enum):
    NOVICE = "Novice"
    PRACTITIONER = "Practitioner"
    PROFICIENT = "Proficient"
    ENGINEERING_LEAD = "Engineering Lead"


class LearningEvent(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Immutable learning event logged whenever a user interacts with learning items."""

    __tablename__ = "learning_events"

    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id"), nullable=False, index=True)
    event_type: Mapped[EventType] = mapped_column(
        Enum(EventType, name="event_type_enum", native_enum=False),
        nullable=False,
        index=True,
    )
    entity_id: Mapped[str] = mapped_column(String(255), nullable=False, index=True)
    entity_type: Mapped[str] = mapped_column(String(50), nullable=False)
    duration_seconds: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    details: Mapped[Dict[str, Any]] = mapped_column(JSON, default=dict, nullable=False)


class StudySession(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Aggregate or recorded study session tracking focused and elapsed study time."""

    __tablename__ = "study_sessions"

    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id"), nullable=False, index=True)
    topic: Mapped[str] = mapped_column(String(100), default="Software Engineering", nullable=False)
    reading_minutes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    coding_minutes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    debugging_minutes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    testing_minutes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    revision_minutes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    focused_minutes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    session_date: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False, index=True)


class ErrorPattern(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Aggregated error patterns identified by the Debugging Intelligence engine."""

    __tablename__ = "error_patterns"

    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id"), nullable=False, index=True)
    category: Mapped[str] = mapped_column(String(100), nullable=False, index=True)  # e.g., "Off-by-One Boundary Condition"
    occurrence_count: Mapped[int] = mapped_column(Integer, default=1, nullable=False)
    avg_fix_minutes: Mapped[float] = mapped_column(Float, default=5.0, nullable=False)
    trend: Mapped[ErrorTrend] = mapped_column(
        Enum(ErrorTrend, name="error_trend_enum", native_enum=False),
        default=ErrorTrend.REPEATING,
        nullable=False,
    )
    last_encountered: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)
    sample_error_message: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    related_concept: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)


class RevisionTask(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Organized revision item generated by the Learning Debt / Revision Planner engine."""

    __tablename__ = "revision_tasks"

    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id"), nullable=False, index=True)
    topic: Mapped[str] = mapped_column(String(255), nullable=False)
    reason: Mapped[RevisionReason] = mapped_column(
        Enum(RevisionReason, name="revision_reason_enum", native_enum=False),
        default=RevisionReason.REPEATED_ERRORS,
        nullable=False,
    )
    urgency: Mapped[RevisionUrgency] = mapped_column(
        Enum(RevisionUrgency, name="revision_urgency_enum", native_enum=False),
        default=RevisionUrgency.HIGH,
        nullable=False,
    )
    explanation: Mapped[str] = mapped_column(Text, nullable=False)
    estimated_minutes: Mapped[int] = mapped_column(Integer, default=20, nullable=False)
    problem_id: Mapped[Optional[str]] = mapped_column(String(36), ForeignKey("problems.id"), nullable=True)
    is_completed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    completed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)


class SkillEvidence(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Verified evidence-backed skill in the Skill Passport."""

    __tablename__ = "skill_evidences"

    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id"), nullable=False, index=True)
    skill_name: Mapped[str] = mapped_column(String(255), nullable=False)
    domain: Mapped[str] = mapped_column(String(100), default="Software Engineering", nullable=False)
    verified_level: Mapped[VerifiedLevel] = mapped_column(
        Enum(VerifiedLevel, name="verified_level_enum", native_enum=False),
        default=VerifiedLevel.PRACTITIONER,
        nullable=False,
    )
    demonstrated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)
    evidence_source: Mapped[str] = mapped_column(String(255), nullable=False)  # e.g. "Practical Project Studio"
    evidence_url: Mapped[str] = mapped_column(String(255), default="/projects", nullable=False)
    confidence_score: Mapped[int] = mapped_column(Integer, default=85, nullable=False)
    is_verified: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
